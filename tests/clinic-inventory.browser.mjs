import express from 'express';
import cookieParser from 'cookie-parser';
import jwt from 'jsonwebtoken';
import assert from 'node:assert/strict';
const {chromium} = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
assert(process.env.CLINIC_TEST_DATABASE_URL, 'Set a local CLINIC_TEST_DATABASE_URL');
assert(['localhost','127.0.0.1'].includes(new URL(process.env.CLINIC_TEST_DATABASE_URL).hostname));
process.env.DATABASE_URL=process.env.CLINIC_TEST_DATABASE_URL;
process.env.ADMIN_JWT_SECRET='local-ui-fixture-only';
const {default:router}=await import('../src/routes/clinicInventory.js');
const {prisma}=await import('../src/db/index.js');
const app=express();app.use(express.json(),cookieParser());app.use('/api/clinic-inventory',router);
app.get('/api/products',async(req,res)=>res.json({success:true,data:await prisma.product.findMany()}));
app.use(express.static('public'));
app.get('/test-ui',(req,res)=>res.send(`<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="/css/clinic-inventory.css"><style>:root{--bg:#faf7f1;--bg-card:#fffdf8;--ink:#263123;--muted:#68705f;--line:#d9d7ca;--venus:#596329}*{box-sizing:border-box}body{margin:0;padding:24px;background:var(--bg);color:var(--ink);font-family:Arial}button{cursor:pointer}.btn{padding:12px 16px;border:1px solid var(--line);border-radius:10px;background:var(--bg-card);color:var(--ink);font-weight:600}.btn.primary{background:var(--venus);color:white}#panel-clinic{max-width:1000px;margin:auto}</style><div id="panel-clinic"></div><script>window.MI_ROL='admin';</script><script src="/js/clinic-inventory.js"></script><script>clinicInventory.load();</script>`));
const server=app.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
const base=`http://127.0.0.1:${server.address().port}`;
const ap=await prisma.appointment.create({data:{clientName:'Clienta de prueba',clientPhone:'test',serviceName:'Facial de prueba',status:'completed',date:'2026-10-20',time:'10:00',startDateTime:new Date(),endDateTime:new Date()}});
const browser=await chromium.launch({channel:'chrome',headless:true});
let supply;
try{
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 await page.context().addCookies([{name:'adm',value:jwt.sign({uid:'test',email:'UI test',role:'admin'},process.env.ADMIN_JWT_SECRET),url:base}]);
 await page.goto(base+'/test-ui');
 await page.getByRole('button',{name:'+ Agregar producto'}).click();
 await page.getByLabel('Nombre del producto').fill('Gel limpiador de prueba');
 await page.getByLabel('Contenido de un frasco (ml)').fill('250');
 await page.getByLabel('Total disponible ahora (ml)').fill('250');
 await page.getByLabel('Avisarme cuando queden (ml)').fill('25');
 await page.locator('dialog').getByRole('button',{name:'Agregar producto',exact:true}).click();
 await page.getByText('250 ml disponibles',{exact:true}).waitFor();
 supply=await prisma.clinicSupply.findFirst({where:{name:'Gel limpiador de prueba'}});
 await page.evaluate(id=>{window.clinicInventory.promptCompleted([id]);},ap.id);
 await page.locator('#ci-use-rows select').selectOption(supply.id);
 await page.getByLabel('Ml usados').fill('3.5');
 await page.getByText('Quedarían 246.5 ml').waitFor();
 await page.screenshot({path:'/tmp/clinic-consumption-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:'/tmp/clinic-consumption-mobile.png'});
 await page.getByRole('button',{name:'Guardar consumo',exact:true}).click();
 await page.getByText('246.5 ml disponibles',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Ver o corregir'}).click();
 await page.getByLabel('Ml usados').fill('2');
 await page.getByRole('button',{name:'Guardar corrección'}).click();
 await page.getByText('248 ml disponibles',{exact:true}).waitFor();
 assert.equal((await prisma.clinicSupply.findUnique({where:{id:supply.id}})).stockMilliMl,248000);
 await page.screenshot({path:'/tmp/clinic-inventory-mobile.png'});
 await page.getByRole('button',{name:'Entrada o ajuste'}).click();
 await page.locator('dialog select[name=kind]').selectOption('adjustment');
 await page.getByLabel('Cantidad (ml)',{exact:true}).fill('249');
 await page.getByLabel('Motivo o referencia').fill('Prueba de saldo insuficiente');
 await page.getByRole('button',{name:'Guardar movimiento'}).click();
 await page.getByText('Stock insuficiente o producto no disponible. Actualiza las cantidades.').waitFor();
 assert(await page.locator('dialog').isVisible());
 assert(!(await page.getByRole('button',{name:'Guardar movimiento'}).isDisabled()));
 console.log('Browser checks passed: create, fractional usage, remaining ml, correction, stock errors, mobile overflow.');
}finally{
 await browser.close();
 if(supply){await prisma.clinicStockMovement.deleteMany({where:{supplyId:supply.id}});await prisma.clinicSupply.delete({where:{id:supply.id}});}
 await prisma.clinicUsage.deleteMany({where:{appointmentId:ap.id}});await prisma.appointment.delete({where:{id:ap.id}});
 await new Promise(r=>server.close(r));await prisma.$disconnect();
}

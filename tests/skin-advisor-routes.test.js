import test from 'node:test';
import assert from 'node:assert/strict';
import express from 'express';
import { createSkinAdvisorRouter } from '../src/routes/skinAdvisor.js';

test('router protects every endpoint and enforces exact origin, JSON, and trusted actor', async t => {
  const calls = [];
  const sent = [];
  let outcome;
  const workflow = Object.fromEntries(['getConfig', 'getRecord', 'createDraft', 'getAssessment', 'generate', 'approve', 'retire', 'services', 'clientView', 'clientLink', 'previewPhoto', 'photoLayers', 'savedLayers'].map(name => [name, async (...args) => { calls.push({ name, args }); return { status: 'ok' }; }]));
  workflow.clientLink = async (...args) => { calls.push({ name: 'clientLink', args }); return { card: { name: 'Daniela', phone: '1' }, url: 'https://venus.example/mi-piel.html?card=c&v=a' }; };
  const app = express();
  app.use('/api/skin-advisor', createSkinAdvisorRouter({ workflow, sendLink: async (card, url) => { sent.push({ card, url }); return outcome; }, expectedOrigin: 'https://venus.example', authenticate: (req, res, next) => { if (req.get('x-test-user')) req.admin = { uid: req.get('x-test-user') }; next(); } }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const base = `http://127.0.0.1:${server.address().port}/api/skin-advisor`;
  for (const path of ['/config', '/services', '/records/r', '/assessments/a']) assert.equal((await fetch(base + path)).status, 401);
  assert.equal((await fetch(base + '/services', { headers: { 'x-test-user': 'staff' } })).status, 200);
  assert.equal(calls.at(-1).name, 'services');
  for (const path of ['/records/r/assessments', '/assessments/a/generate', '/assessments/a/approve', '/records/r/photos/p/preview']) assert.equal((await fetch(base + path, { method: 'POST' })).status, 401);
  const post = headers => fetch(base + '/assessments/a/approve', { method: 'POST', headers: { 'x-test-user': 'staff', ...headers }, body: JSON.stringify({ actorId: 'owner', version: 2 }) });
  assert.equal((await fetch(base + '/services', { headers: { 'x-test-user': 'staff', origin: 'https://evil.example' } })).status, 403);
  for (const path of ['/config', '/records/r', '/assessments/a']) {
    for (const method of ['GET', 'HEAD']) {
      assert.equal((await fetch(base + path, { method, headers: { 'x-test-user': 'staff', origin: 'https://sibling.venus.example' } })).status, 403);
      assert.equal((await fetch(base + path, { method, headers: { 'x-test-user': 'staff', origin: 'https://venus.example' } })).status, 200);
      assert.equal((await fetch(base + path, { method, headers: { 'x-test-user': 'staff' } })).status, 200);
    }
  }
  assert.equal((await post({ 'content-type': 'application/json' })).status, 403);
  assert.equal((await post({ origin: 'https://evil.example', 'content-type': 'application/json' })).status, 403);
  assert.equal((await post({ origin: 'https://venus.example', 'content-type': 'text/plain' })).status, 415);
  const response = await post({ origin: 'https://venus.example', 'content-type': 'application/json' });
  assert.equal(response.status, 200);
  assert.equal(calls.at(-1).args[0], 'staff');
  assert.equal(calls.at(-1).name, 'approve');
  assert.deepEqual(await response.json(), { success: true, data: { status: 'ok' } });
  const retire = headers => fetch(base + '/assessments/a/retire', { method: 'POST', headers: { 'x-test-user': 'staff', ...headers }, body: JSON.stringify({ version: 3 }) });
  assert.equal((await retire({ 'content-type': 'application/json' })).status, 403);
  assert.equal((await retire({ origin: 'https://venus.example', 'content-type': 'application/json' })).status, 200);
  assert.equal(calls.at(-1).name, 'retire');
  assert.deepEqual(calls.at(-1).args, ['staff', 'a', { version: 3 }]);
  assert.equal((await fetch(base + '/assessments/a/client-view')).status, 401);
  const view = await fetch(base + '/assessments/a/client-view', { headers: { 'x-test-user': 'staff' } });
  assert.equal(view.status, 200);
  assert.equal(view.headers.get('cache-control'), 'private, no-store');
  assert.equal(calls.at(-1).name, 'clientView');
  assert.deepEqual(calls.at(-1).args, ['staff', 'a']);
  const preview = headers => fetch(base + '/records/r/photos/p/preview', { method: 'POST', headers: { 'x-test-user': 'staff', ...headers }, body: JSON.stringify({ mode: 'red_contrast', actorId: 'owner' }) });
  assert.equal((await preview({ 'content-type': 'application/json' })).status, 403);
  assert.equal((await preview({ origin: 'https://evil.example', 'content-type': 'application/json' })).status, 403);
  assert.equal((await preview({ origin: 'https://venus.example', 'content-type': 'text/plain' })).status, 415);
  const rendered = await preview({ origin: 'https://venus.example', 'content-type': 'application/json' });
  assert.equal(rendered.status, 200);
  assert.equal(rendered.headers.get('cache-control'), 'private, no-store');
  assert.equal(calls.at(-1).name, 'previewPhoto');
  assert.deepEqual(calls.at(-1).args.slice(0, 3), ['staff', 'r', 'p']);
  const layerRequest = headers => fetch(base + '/records/r/photos/p/layers', { method: 'POST', headers, body: '{}' });
  assert.equal((await layerRequest({})).status, 401);
  assert.equal((await layerRequest({ 'x-test-user': 'staff', origin: 'https://evil.example', 'content-type': 'application/json' })).status, 403);
  const layers = await layerRequest({ 'x-test-user': 'staff', origin: 'https://venus.example', 'content-type': 'application/json' });
  assert.equal(layers.status, 200);
  assert.equal(layers.headers.get('cache-control'), 'private, no-store');
  assert.equal(calls.at(-1).name, 'photoLayers');
  assert.deepEqual(calls.at(-1).args, ['staff', 'r', 'p']);
  assert.equal((await fetch(base + '/records/r/photos/p/layers')).status, 401);
  assert.equal((await fetch(base + '/records/r/photos/p/layers', { headers: { 'x-test-user': 'staff', origin: 'https://evil.example' } })).status, 403);
  const saved = await fetch(base + '/records/r/photos/p/layers', { headers: { 'x-test-user': 'staff' } });
  assert.equal(saved.status, 200);
  assert.equal(saved.headers.get('cache-control'), 'private, no-store');
  assert.equal(calls.at(-1).name, 'savedLayers');
  assert.deepEqual(calls.at(-1).args, ['staff', 'r', 'p']);
  const send = headers => fetch(base + '/assessments/a/send-link', { method: 'POST', headers: { 'x-test-user': 'staff', ...headers }, body: '{}' });
  assert.equal((await send({ 'content-type': 'application/json' })).status, 403);
  assert.equal(sent.length, 0);
  const sentRes = await send({ origin: 'https://venus.example', 'content-type': 'application/json' });
  assert.equal(sentRes.status, 200);
  assert.deepEqual(await sentRes.json(), { success: true, data: { sent: true } });
  assert.deepEqual(sent, [{ card: { name: 'Daniela', phone: '1' }, url: 'https://venus.example/mi-piel.html?card=c&v=a' }]);
  assert.deepEqual(calls.at(-1).args, ['staff', 'a']);
  assert.equal(calls.at(-1).name, 'clientLink');
  outcome = { success: false };
  const failed = await send({ origin: 'https://venus.example', 'content-type': 'application/json' });
  assert.equal(failed.status, 502);
  assert.equal((await failed.json()).error, 'send_failed');
});
